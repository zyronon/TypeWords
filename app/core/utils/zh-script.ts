const T2S_PAIRS: Record<string, string> = {}
for (const [s, t] of Object.entries(S2T_PAIRS)) {
  if (s !== t && !(t in T2S_PAIRS)) T2S_PAIRS[t] = s
}

const s2tTable = new Map(Object.entries(S2T_PAIRS))
const t2sTable = new Map(Object.entries(T2S_PAIRS))

function mapChars(text: string, table: Map<string, string>): string {
  if (!text) return text
  let out = ''
  for (const ch of text) {
    out += table.get(ch) ?? ch
  }
  return out
}

export function toTraditional(text: string): string {
  return mapChars(text, s2tTable)
}

export function toSimplified(text: string): string {
  return mapChars(text, t2sTable)
}

export type DictScript = 'zh-CN' | 'zh-TW'

export function convertDictText(text: string, script: DictScript): string {
  if (!text) return text
  return script === 'zh-TW' ? toTraditional(text) : toSimplified(text)
}
